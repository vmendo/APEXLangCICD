#!/usr/bin/env python3
"""Remove previous-cycle logs before any current cleanup stage writes its logs."""
import shutil
import sys
from pathlib import Path


def reset_logs(demo_home):
    home = Path(demo_home).resolve(strict=True)
    logs = home / 'logs'
    if logs.is_symlink():
        raise ValueError('Refusing to clear a symlinked logs directory.')
    if logs.exists() and not logs.is_dir():
        raise ValueError('The logs path must be a directory.')
    if logs.exists():
        for child in logs.iterdir():
            if child.is_symlink() or not child.is_dir():
                child.unlink()
            else:
                shutil.rmtree(child)
    else:
        logs.mkdir(mode=0o700)
    print('Previous-cycle logs removed. Logs generated by this cleanup will be retained.')


if __name__ == '__main__':
    if len(sys.argv) != 2:
        raise SystemExit('Usage: reset_logs.py <demo_home>')
    try:
        reset_logs(sys.argv[1])
    except (OSError, ValueError) as error:
        raise SystemExit(f'Log reset failed: {error}')
