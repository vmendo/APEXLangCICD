#!/usr/bin/env bash
# Shared defaults. Override through environment variables or config/local.env.
DEMO_HOME="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
if [[ -f "$DEMO_HOME/config/local.env" ]]; then
  source "$DEMO_HOME/config/local.env"
fi
PROJECTS_HOME="${PROJECTS_HOME:-$DEMO_HOME/projects}"
PROJECT_NAME="${PROJECT_NAME:-TrainingHubCICD}"
PROJECT_DIR="$PROJECTS_HOME/$PROJECT_NAME"
SQLCL_BIN="$DEMO_HOME/tools/sqlcl-26.3/bin/sql"
DB_CONNECT_DEV="${DB_CONNECT_DEV:-ADB_LOCAL_DEMO}"
DB_CONNECT_ADMIN="${DB_CONNECT_ADMIN:-ADMIN_ADBFREE}"
DB_CONNECT_PRO="${DB_CONNECT_PRO:-DEMO_ADBFREE}"
SCHEMA_NAME="${SCHEMA_NAME:-DEMO}"
SCHEMA_NAME_PRO="${SCHEMA_NAME_PRO:-DEMO}"
APEX_WORKSPACE_DEV="${APEX_WORKSPACE_DEV:-DEMO}"
APEX_WORKSPACE_PRO="${APEX_WORKSPACE_PRO:-DEMO}"
APEX_APP_ID="${APEX_APP_ID:-110}"
APEX_APP_ID_PRO_PREFERRED="${APEX_APP_ID_PRO_PREFERRED:-${APEX_APP_ID_PRO:-$APEX_APP_ID}}"
APEX_APP_ID_PRO="${APEX_APP_ID_PRO:-$APEX_APP_ID_PRO_PREFERRED}"
GITHUB_REPO="${GITHUB_REPO:-vmendo/apex_ci_cd_demo}"
GITHUB_URL="${GITHUB_URL:-https://github.com/$GITHUB_REPO.git}"
PROJECT_BRANCH="${PROJECT_BRANCH:-main}"
RELEASE_TAG_PREFIX="${RELEASE_TAG_PREFIX:-v}"
SQLCL_TIMEOUT="${SQLCL_TIMEOUT:-180}"
PR_POLL_SECONDS="${PR_POLL_SECONDS:-5}"
SQLCL_DEPLOY_TIMEOUT="${SQLCL_DEPLOY_TIMEOUT:-1800}"
export DEMO_HOME PROJECTS_HOME PROJECT_NAME PROJECT_DIR SQLCL_BIN DB_CONNECT_DEV DB_CONNECT_PRO DB_CONNECT_ADMIN
export SCHEMA_NAME SCHEMA_NAME_PRO APEX_WORKSPACE_DEV APEX_WORKSPACE_PRO APEX_APP_ID APEX_APP_ID_PRO APEX_APP_ID_PRO_PREFERRED
export GITHUB_REPO GITHUB_URL PROJECT_BRANCH RELEASE_TAG_PREFIX SQLCL_TIMEOUT
export PR_POLL_SECONDS
export SQLCL_DEPLOY_TIMEOUT
